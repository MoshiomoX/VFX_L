// ============================================================
// ExpOrbComponent.h
// 敵が落とす経験値のかたまり。
//
// CollisionSystem を使わない：
//   必要なのはプレイヤーとの距離だけで、形状の交差判定は要らない。
//   数が多くなる想定なので、CPU 総当たりの衝突判定に載せると
//   投射物と同じくそこが先に詰まる。
//   投射物に Rigidbody を付けなかったのと同じ判断。
//
// 消滅時間は持たない：
//   取り逃しを無くし、戦闘が落ち着いてから回収できるようにする。
//   「今すぐ取りに行くか」の緊張感より、
//   組み上げた魔法を見る余裕を優先する。
// ============================================================
#pragma once
#include <SimpleMath.h>

struct ExpOrbComponent
{
    float amount = 10.0f;          // 拾った時に入る経験値

    // 吸い寄せ中かどうか。一度入ったら範囲外へ出ても追い続ける。
    // 範囲の境界で吸ったり止まったりを繰り返すのを防ぐため。
    bool  attracted = false;

    float speed = 0.0f;            // 現在の吸い寄せ速度
    float spawnDelay = 0.25f;      // 湧いた直後は吸われない猶予

    // 湧いた瞬間に少し飛び散らせるための初速
    DirectX::SimpleMath::Vector3 velocity = { 0.0f, 0.0f, 0.0f };
};