// ============================================================
// EnemyTags.h
// 敵の「身分」を表す空タグ。行動（ChaseAI 等）とは独立。
//
// 身分と行動を分ける理由:
//   SpawnDirector が数える・押し出すのは「雑魚という身分」であって、
//   「追跡型という行動」ではない。将来 RangedAI の雑魚が増えても
//   SpawnDirector は一行も変わらない。
//
// 使い分け:
//   MobTag   . 雑魚。湧き予算に数えられ、溢れたら押し出される
//   EliteTag . 精英とボス。予算外・押し出し対象外・絶対に消えない
//   ※どちらも付いていない敵は存在させない（無敵の的は EliteTag）
//
// 判定の使い分け（既存と衝突しない）:
//   「敵かどうか」        → Layer_Enemy（衝突・索敵はこれまで通り）
//   「湧き管理の対象か」  → MobTag / EliteTag（SpawnDirector 専用）
//   「どう動くか」        → ChaseAIComponent 等（各 AISystem 専用）
// ============================================================
#pragma once

struct MobTag {};     // 雑魚
struct EliteTag {};   // 精英・ボス・計測用の的（消えない側）