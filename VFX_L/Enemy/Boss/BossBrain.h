// Boss の次の技を決める（規則版。2026-10-07、ユーザー「Boss の技を作る」。選び方は推奨の「距離 + 技ごとの冷却」）。
//   ・技ごとに冷却（使ってから cooldown 秒は選ばない）。HP が狂暴の線を切った後は冷却 × enragedCooldownMul
//   ・プレイヤーまでの距離で 近い（< nearDist）/ 中 / 遠い（> farDist）の 3 段に分け、段ごとの重みで抽選
//     （遠ければ突進・投石雨、近ければ重撃・衝撃波が出やすい）。minDist〜maxDist の外の技は選ばない
//   ・直前と同じ技は、他に選べる技がある限り選ばない
// 後で Jev（AI の判断。jev-boss-ai-plan）に替える時はこのクラスの Choose だけを差し替える
// ============================================================
#pragma once
#include <random>

enum class BossMove : int
{
    None = -1,
    Slam = 0,     // 重撃：プレイヤーの足元に赤い輪を 3 つ（2026-10-03 からの技）
    RockRain,     // 投石雨：プレイヤーの周りのばらばらな所に小さい輪、岩が落ちる（走って避ける）
    Shockwave,    // 衝撃波：Boss が地面を叩き、地面を這う光の帯が外へ広がる（跳んで避ける）
    Charge,       // 突進：道筋の輪が出た後、Boss が一直線に走る（横へ避ける）
    Summon,       // 召喚：Boss が止まって吠え、周りの小さな輪から雑魚・自爆兵が湧く（2026-10-07）
    // ---- 砂の守護者（砂漠の Boss）だけの技（2026-10-24。BossType::SandGuardian の時だけ enabled）----
    SandSpear,    // 砂の槍：Boss からプレイヤーへ線上に輪 → 足元から先へ石のトゲが突き出る（横へ避ける）
    Burrow,       // 潜砂奇襲：砂に潜って（撃てない）砂丘だけがプレイヤーを追う → 止まって輪 → 飛び出して叩く（輪から走って出る）
    Quicksand,    // 流沙：Boss の周りに回る砂の渦。中では遅くなり中心へ引かれる（跳んでいる間は効かない）。渦は技の後も残る
    // ---- 大サソリ（砂漠 2 面目）だけの技（2026-10-26。BossType::Scorpion の時だけ enabled）----
    Sting,        // 毒針：向きを固めて帯の予告 → 短く突っ込んで尾で刺す。当たると毒（しばらく走りが遅い）。横へ避ける
    ClawSweep,    // 鋏の薙ぎ払い：正面の扇の予告 → 鋏で薙ぐ（吹き飛ばし）。扇から出る
    // ---- 墓守の騎士（遺跡 1 面目）だけの技（2026-10-26。BossType::CryptKnight の時だけ enabled）----
    ChainPull,    // 双鎖：向きを固めて 2 本の帯の予告 → 鎖を 2 本投げ、掛かればプレイヤーを足元へ引き寄せ → すぐ重撃。帯の間 / 外へ
    // ---- 月下の狼人（草原 2 面目）だけの技（2026-10-26。BossType::Werewolf の時だけ enabled）----
    Pounce,       // 飛びかかり：しゃがむ → プレイヤーの所へ跳ぶ（着地点に輪）→ 着地で周り（輪から走って出る）
    ClawCombo,    // 爪の三連：短い帯の予告 → 短く突っ込んで斬る × 3（狂暴で 5。毎回向きを取り直す）。横へ
    Howl,         // 遠吠え：止まって吠える → 周りから雑魚が湧き、しばらく技の間が半分
    // ---- 雷鳴の雄鹿（草原 3 面目）だけの技（2026-10-29。BossType::Stag の時だけ enabled。共通は突進だけ残す）----
    AntlerToss,   // 角の振り上げ：向きを固めて頭を下げる（正面の扇）→ 角で前上へすくい上げ、扇の中なら高く吹き上げる。横・後ろへ
    AntlerBolt,   // 角の雷撃：向きを固めて扇に並ぶ帯の予告 → 角から帯に沿って雷が走る（狂暴で本数が増える）。帯の間 / 扇の外へ
    // ---- 砂嵐の魔神（砂漠 3 面目）だけの技（2026-10-29。BossType::Djinn の時だけ enabled。一段目 = 浮いて離れて撃つ、二段目 = 降りて殴る）----
    DustDevils,   // 砂嵐召喚：プレイヤーの周り（始めた時の足元が中心）に砂旋が 3 本（二段目 4 本）現れ、回りながら輪を縮める。輪の外へ走って出る。砂旋は技の後も残る
    DjinnBreath,  // 炎の息：向きを固めて扇の予告 → 口から砂混じりの炎を吐き、扇がゆっくりプレイヤーを追う。横へ回り込むか扇の外へ
    DjinnShift,   // 砂渡り：砂に溶けて沈み（撃てない）、地面の下をプレイヤーの向こう側へ抜けて浮かび上がり、すぐ炎の息
    SandFist,     // 砂の拳（二段目）：両腕を振り上げて正面の扇の予告 → 地面へ叩き付ける。扇から出る
    // ---- 骸の王（遺跡 3 面目）だけの技（2026-10-29。BossType::BoneKing の時だけ enabled。間合いを取る術師。見た目は闇から這い出る冠の巨大な骸骨）----
    CurseOrbs,    // 呪いの玉：両腕を上げて暗い紫の玉を扇に 5 つ（狂暴 7）放つ。玉はゆっくりプレイヤーを追い、触れると爆ぜる。走って振り切る
    RaiseDead,    // 大起尸：プレイヤーの周りの死体（最近倒した敵）が一斉に骸骨になって起き上がる。足りなければ周りの地面から
    ShadowStep,   // 影へ消える：闇に沈み（撃てない）、プレイヤーの周りの別の側へ回り込んで浮かび上がり、すぐ呪いの玉
    CurseFloor,   // 呪いの床：プレイヤーの足元に紫の渦が広がる。中では遅く・中心へ引かれ、地面に居る間じわじわ減る（跳べば効かない）
    // ---- 石の守護獣（遺跡 2 面目）だけの技（2026-10-29。BossType::StoneBeast の時だけ enabled。一段目 = 飛んで、二段目 = 降りて）----
    BeastDive,    // 急降下：空中で向きを固めて帯の予告 → 帯に沿って低く滑空して突っ込む。横へ避ける
    PetrifyBreath,// 石化の息：扇の予告 → 灰色の息を吐き、扇がゆっくりプレイヤーを追う。浴びるほど足が石になって遅くなり、溜まり切ると少しの間動けない
    WingGust,     // 翼の突風：翼を大きく振り上げ（正面の扇）→ 打ち下ろして前へ突風。扇の中なら高く吹き飛ばされる。扇の外へ
    TailSweep,    // 尾の薙ぎ払い（二段目）：周りに輪 → 体ごと一回転して尾の岩槌で薙ぐ。跳べば避けられる / 輪から出る
    SkyCrush,     // 天からの圧殺（一段目）：高く舞い上がり、影がプレイヤーを追う → 止まった影へ落ちて叩き潰し、衝撃波（影から出て、衝撃波を跳ぶ）
    FeatherShards,// 石羽の散弾：扇に石の羽根を 2 回。2 回目は 1 回目の隙間を通る（隙間へ動き、次は戻る）
    Count
};

